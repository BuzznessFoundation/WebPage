/**
 * Pull Contentful entries → generate src/data/*.ts
 * Run: npx tsx scripts/contentful-pull.ts
 * Requiere: CONTENTFUL_DELIVERY_ACCESS_TOKEN en .env.local
 */
import { createClient } from 'contentful'
import { config } from 'dotenv'
import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'fs'
import { resolve } from 'path'

config({ path: resolve('.env.local') })

const client = createClient({
    space: process.env.CONTENTFUL_SPACE_ID!,
    accessToken: process.env.CONTENTFUL_DELIVERY_ACCESS_TOKEN!,
    environment: process.env.CONTENTFUL_ENVIRONMENT ?? 'master',
})

function val(fields: Record<string, unknown>, key: string): string {
    return String(fields[key] ?? '')
}

function arr(fields: Record<string, unknown>, key: string): string[] {
    const v = fields[key]
    return Array.isArray(v) ? v.map(String) : []
}

const header = '// Generated by scripts/contentful-pull.ts — do not edit manually\n\n'

// ─── Guard anti-drift ──────────────────────────────────────────────────────────
// Congela los datos commiteados: si el archivo en disco tiene MÁS entradas que
// Contentful, escribir lo traería destruiría contenido publicado. Se aborta.

/**
 * Cuenta las entradas de un array exportado en un archivo TS/JSON generado.
 * Soporta el formato JSON.stringify (`.ts` recién generado) y literales TS
 * con comillas simples / keys sin comillas (archivos commiteados a mano).
 * Devuelve `null` si no encuentra el array o no lo puede interpretar.
 */
function countEntries(text: string): number | null {
    const match = /export\s+const\s+\w+[^=]*=\s*\[/.exec(text)
    if (!match) return null

    let i = match.index + match[0].length - 1 // posición del primer `[`
    let arrDepth = 0
    let objDepth = 0
    let count = 0
    let inString: string | null = null

    for (; i < text.length; i++) {
        const ch = text[i]
        if (inString) {
            if (ch === '\\') {
                i++
                continue
            }
            if (ch === inString) inString = null
            continue
        }
        if (ch === "'" || ch === '"' || ch === '`') {
            inString = ch
            continue
        }
        if (ch === '/' && text[i + 1] === '/') {
            while (i < text.length && text[i] !== '\n') i++
            continue
        }
        if (ch === '/' && text[i + 1] === '*') {
            i += 2
            while (i < text.length && !(text[i] === '*' && text[i + 1] === '/')) i++
            i++
            continue
        }
        if (ch === '[') {
            arrDepth++
        } else if (ch === ']') {
            arrDepth--
            if (arrDepth === 0) break
        } else if (ch === '{') {
            if (arrDepth === 1 && objDepth === 0) count++
            objDepth++
        } else if (ch === '}') {
            objDepth--
        }
    }
    return count
}

interface WriteResult {
    fileName: string
    written: boolean
    /** Entradas commiteadas en disco, o null si no se pudieron contar. */
    existing: number | null
    /** Entradas que trae Contentful. */
    incoming: number
    /** Motivo accionable cuando el archivo quedó protegido. */
    reason?: string
}

/**
 * Escribe el archivo generado sólo si no destruye datos commiteados.
 * Es por-archivo y NO lanza: retorna un resultado para que el resto de los
 * pulls puedan completarse. Si el archivo existente tiene más entradas que
 * las que devuelve Contentful, queda protegido (no se escribe) y se informa.
 */
function writeGuarded(fileName: string, content: string, newCount: number): WriteResult {
    const file = resolve('src/data', fileName)

    if (existsSync(file)) {
        const existing = countEntries(readFileSync(file, 'utf8'))
        if (existing === null) {
            return {
                fileName,
                written: false,
                existing: null,
                incoming: newCount,
                reason:
                    `Guard anti-drift: no se pudo contar las entradas de src/data/${fileName}. ` +
                    `Se aborta la escritura para no sobrescribir el archivo sin poder verificar. ` +
                    `Revisá el archivo a mano y decidí: sincronizar o congelar.`,
            }
        }
        if (existing > newCount) {
            return {
                fileName,
                written: false,
                existing,
                incoming: newCount,
                reason:
                    `Guard anti-drift: src/data/${fileName} tiene ${existing} entrada(s) commiteada(s), ` +
                    `pero Contentful devuelve ${newCount}. ` +
                    `Sincronizar eliminaría ${existing - newCount} entrada(s) en producción. ` +
                    `Escritura abortada: el archivo commiteado queda intacto. ` +
                    `Decidí a mano: (a) sincronizar — borrar las entradas faltantes en Contentful ` +
                    `o actualizar el archivo — o (b) congelar — no correr este pull.`,
            }
        }
    }

    mkdirSync(resolve('src/data'), { recursive: true })
    writeFileSync(file, content)
    return { fileName, written: true, existing: null, incoming: newCount }
}

// ─── Services ─────────────────────────────────────────────────────────────────

async function pullServices() {
    const entries = await client.getEntries({
        content_type: 'service',
        order: ['fields.order'],
        limit: 100,
    })
    const items = entries.items.map((e) => {
        const f = e.fields
        return {
            id: `${e.sys.id}`,
            eyebrow: val(f, 'eyebrow'),
            title: val(f, 'title'),
            description: val(f, 'description'),
            tags: arr(f, 'tags'),
        }
    })

    const content = `${header}import type { Service } from '@/types/service'\n
export const services: Service[] = ${JSON.stringify(items, null, 2)}\n`

    const result = writeGuarded('services.ts', content, items.length)
    if (result.written) console.log(`  ✓ services.ts (${items.length} entries)`)
    return result
}

// ─── Projects ─────────────────────────────────────────────────────────────────

async function pullProjects() {
    const entries = await client.getEntries({
        content_type: 'project',
        order: ['fields.order'],
        limit: 100,
    })
    const items = entries.items.map((e) => {
        const f = e.fields
        return {
            id: e.sys.id,
            title: val(f, 'title'),
            category: val(f, 'category'),
            description: val(f, 'description'),
            stack: arr(f, 'stack'),
            status: val(f, 'status') as 'activo' | 'en desarrollo' | 'completado',
            href: val(f, 'repoUrl') || undefined,
        }
    })

    const content = `${header}import type { Project } from '@/types/project'\n
export const projects: Project[] = ${JSON.stringify(items, null, 2)}\n`

    const result = writeGuarded('projects.ts', content, items.length)
    if (result.written) console.log(`  ✓ projects.ts (${items.length} entries)`)
    return result
}

// ─── Stats ────────────────────────────────────────────────────────────────────

async function pullStats() {
    const entries = await client.getEntries({
        content_type: 'stat',
        order: ['fields.order'],
        limit: 20,
    })
    const items = entries.items.map((e) => {
        const f = e.fields
        return {
            value: val(f, 'value'),
            label: val(f, 'label'),
        }
    })

    const content = `${header}export interface Stat {
  value: string
  label: string
}

export const stats: Stat[] = ${JSON.stringify(items, null, 2)}\n`

    const result = writeGuarded('stats.ts', content, items.length)
    if (result.written) console.log(`  ✓ stats.ts (${items.length} entries)`)
    return result
}

// ─── Blog Posts ───────────────────────────────────────────────────────────────

async function pullBlogPosts() {
    const entries = await client.getEntries({
        content_type: 'blogPost',
        order: ['-fields.publishedAt'],
        limit: 100,
    })
    const items = entries.items.map((e) => {
        const f = e.fields
        return {
            id: e.sys.id,
            title: val(f, 'title'),
            slug: val(f, 'slug'),
            excerpt: val(f, 'excerpt'),
            body: val(f, 'body'),
            publishedAt: val(f, 'publishedAt'),
            tags: arr(f, 'tags'),
        }
    })

    const content = `${header}import type { BlogPost } from '@/types/blogPost'\n
export const blogPosts: BlogPost[] = ${JSON.stringify(items, null, 2)}\n`

    const result = writeGuarded('blogPosts.ts', content, items.length)
    if (result.written) console.log(`  ✓ blogPosts.ts (${items.length} entries)`)
    return result
}

// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
    console.log('Pulling from Contentful...\n')
    const results = await Promise.all([
        pullServices(),
        pullProjects(),
        pullStats(),
        pullBlogPosts(),
    ])

    const protectedFiles = results.filter((r) => !r.written)
    if (protectedFiles.length > 0) {
        console.error('\n⚠️  Guard anti-drift: archivos protegidos (NO se escribieron):')
        for (const r of protectedFiles) {
            if (r.existing === null) {
                console.error(`  • src/data/${r.fileName}: no se pudo contar las entradas.`)
            } else {
                console.error(
                    `  • src/data/${r.fileName}: commiteado=${r.existing}, ` +
                        `Contentful=${r.incoming}, se perderían=${r.existing - r.incoming}.`
                )
            }
            console.error(`    ${r.reason}`)
        }
        console.error(
            `\n${protectedFiles.length} archivo(s) quedaron intactos. ` +
                `Decidí a mano: sincronizar (actualizar Contentful/el archivo) o congelar.`
        )
        process.exitCode = 1
        return
    }

    console.log('\nDone.')
}

main().catch((e) => {
    console.error('Error:', e.message)
    process.exit(1)
})
